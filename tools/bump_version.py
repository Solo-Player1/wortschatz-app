#!/usr/bin/env python3
"""Bump the app version everywhere at once.

Usage:  python tools/bump_version.py 1.1.0 [--notes "what changed"]

Updates: package.json "version", android/app/build.gradle versionCode (+1) / versionName,
www/js/version.js (what the app shows and compares against the update manifest) and
updates/manifest.json (version, versionCode, apk download URL, notes, date).
"""
import json, os, re, sys, datetime
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = 'Solo-Player1/wortschatz-app'   # GitHub repo that hosts the releases (updates/manifest.json "apk")

def main():
    if len(sys.argv) < 2 or not re.fullmatch(r'\d+\.\d+\.\d+', sys.argv[1]):
        print(__doc__); sys.exit(1)
    ver = sys.argv[1]
    notes = ''
    if '--notes' in sys.argv:
        notes = sys.argv[sys.argv.index('--notes') + 1]
    # package.json
    pj = os.path.join(ROOT, 'package.json')
    p = json.load(open(pj, encoding='utf-8')); p['version'] = ver
    json.dump(p, open(pj, 'w', encoding='utf-8'), ensure_ascii=False, indent=2); open(pj, 'a', encoding='utf-8').write('\n')
    # build.gradle
    bg = os.path.join(ROOT, 'android', 'app', 'build.gradle')
    g = open(bg, encoding='utf-8').read()
    code = int(re.search(r'versionCode\s+(\d+)', g).group(1)) + 1
    g = re.sub(r'versionCode\s+\d+', f'versionCode {code}', g)
    g = re.sub(r'versionName\s+"[^"]*"', f'versionName "{ver}"', g)
    open(bg, 'w', encoding='utf-8').write(g)
    # www/js/version.js
    vj = os.path.join(ROOT, 'www', 'js', 'version.js')
    open(vj, 'w', encoding='utf-8').write(
        '// generated by tools/bump_version.py - do not edit by hand\n'
        f"export const APP_VERSION = '{ver}';\nexport const VERSION_CODE = {code};\n"
        f"export const UPDATE_MANIFEST_URL = 'https://raw.githubusercontent.com/{REPO}/main/updates/manifest.json';\n")
    # updates/manifest.json
    md = os.path.join(ROOT, 'updates'); os.makedirs(md, exist_ok=True)
    man = {
        'version': ver, 'versionCode': code,
        'apk': f'https://github.com/{REPO}/releases/download/v{ver}/Wortschatz-v{ver}.apk',
        'notes': notes, 'date': datetime.date.today().isoformat(),
        'dataVersion': json.load(open(os.path.join(ROOT, 'www', 'data', 'lessons.json'), encoding='utf-8')).get('version', 1),
    }
    json.dump(man, open(os.path.join(md, 'manifest.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print(f'version {ver} (versionCode {code}) written to package.json, build.gradle, www/js/version.js, updates/manifest.json')

if __name__ == '__main__':
    main()
